"""
train_sandbox_cddp.py
=====================
Phase 5: Continuous CDDP with checkpointing and trajectory visualization.

This script extends the differentiable HOCBF-DDPG sandbox with a strict
pre-training phase followed by the two-critic training structure needed to
avoid the covariate shift observed in the earlier gridworld experiments:

  - Pre-training phase: train only Actor + Z_free under strict S=0 projection
    so the policy learns basic CBF-compatible navigation before Z_deon labels
    are collected.

  - Z_free(s, a): standard utilitarian action-value critic, trained only on
    utilitarian-buffer rollouts.

  - Z_deon(s): deontic critic, trained only on even-episode rollouts collected
    under strict safety S=0. It predicts P_cat(s), the probability of episode
    failure under strict compliance.

Rollout collection is deliberately bifurcated. Deontic data never contains
states generated by a relaxed shield, so Z_deon is not taught that unsafe
shortcuts are safe. Utilitarian data gets the learned dynamic boundary:

    S(s) = clip(Z_deon(s) / P_ref, 0, 1), where P_ref = 0.2.

Run from repo root:
  python sandbox/train_sandbox_cddp.py

For a quick smoke test:
  python sandbox/train_sandbox_cddp.py --episodes 4 --pretrain-episodes 2 --warmup-steps 0
"""

