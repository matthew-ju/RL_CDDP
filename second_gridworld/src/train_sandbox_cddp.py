    parser.add_argument("--best-criterion", choices=["composite", "success"], default="composite")
    parser.add_argument(
        "--train-every",
        type=int,
        default=TRAIN_EVERY,
        help="Run learner updates every N vectorized environment steps.",
    )
    parser.add_argument(
        "--gradient-steps",
        type=int,
        default=GRADIENT_STEPS,
        help="Number of learner update passes each time training is triggered.",
    )
    return parser.parse_args()


