def save_best_checkpoints(agent: CDDPAgent) -> None:
    """Persist the best CDDP-phase networks for final evaluation."""
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    torch.save(agent.actor.state_dict(), os.path.join(CHECKPOINT_DIR, "cddp_actor_best.pt"))
    torch.save(agent.z_free.state_dict(), os.path.join(CHECKPOINT_DIR, "cddp_z_free_best.pt"))
    torch.save(agent.z_deon.state_dict(), os.path.join(CHECKPOINT_DIR, "cddp_z_deon_best.pt"))


def load_best_checkpoints(agent: CDDPAgent) -> bool:
    """Load the best CDDP-phase weights if they have been saved."""
    actor_path = os.path.join(CHECKPOINT_DIR, "cddp_actor_best.pt")
    z_free_path = os.path.join(CHECKPOINT_DIR, "cddp_z_free_best.pt")
    z_deon_path = os.path.join(CHECKPOINT_DIR, "cddp_z_deon_best.pt")
    if not all(os.path.exists(path) for path in (actor_path, z_free_path, z_deon_path)):
        return False

    try:
        agent.actor.load_state_dict(torch.load(actor_path, map_location=DEVICE))
        agent.z_free.load_state_dict(torch.load(z_free_path, map_location=DEVICE))
        agent.z_deon.load_state_dict(torch.load(z_deon_path, map_location=DEVICE))
    except RuntimeError as exc:
        print(f"  Best checkpoint is incompatible with current architecture: {exc}")
        return False
    return True


@torch.no_grad()
def rollout_eval_trajectory(
    env: DifferentiablePointMassEnv,
    agent: CDDPAgent,
    clock_max_steps: int,
    rollout_cap: int,
) -> tuple[list[tuple[float, float]], list[float]]:
    """Roll out from a fixed in-distribution start and record positions/stakes."""
    state = torch.tensor([EVAL_START_STATE], dtype=torch.float32, device=DEVICE)
    env.reset(state, max_steps=clock_max_steps)

    positions: list[tuple[float, float]] = [tuple(env.state[0, :2].cpu().tolist())]
    stakes_values: list[float] = []

    for _ in range(rollout_cap):
        s = env.state.squeeze(0).detach().clone()
        stakes = agent.stakes_from_deon(s.unsqueeze(0), detach=True)

        u_safe = agent.select_action(s, stakes=stakes, ou_noise=None)
        out = env.step(u_safe.unsqueeze(0))

        stakes_values.append(stakes.item())
        positions.append(tuple(out["state"][0, :2].detach().cpu().tolist()))

        if out["goal_reached"].item():
            break
        if env.current_step >= clock_max_steps:
            break

    return positions, stakes_values


def estimate_unobstructed_min_steps() -> int:
    """Estimate the fastest goal reach in open space under current dynamics.

    This ignores the obstacle and CBF but includes dt, U_MAX, v_max, and the
    environment's soft velocity saturation. It is a physical lower bound for
    the selected evaluation start, not a learned-policy guarantee.
    """
    pos = torch.tensor(EVAL_START_STATE[:2], dtype=torch.float32)
    vel = torch.zeros(2, dtype=torch.float32)

    for step in range(1, LONG_CLOCK_STEPS + 1):
        direction = torch.sign(GOAL.cpu() - pos)
        action = U_MAX * direction
        pos = pos + DT * vel
        vel = V_MAX_ENV * torch.tanh((vel + DT * action) / V_MAX_ENV)
        if torch.norm(pos - GOAL.cpu()).item() < GOAL_TOL:
            return step

    raise RuntimeError("Unobstructed minimum-step estimate failed to reach the goal.")


def eval_clock_config() -> tuple[int, int]:
    min_steps = estimate_unobstructed_min_steps()
    return min_steps, TIGHT_CLOCK_STEPS


def add_stakes_path(
    ax: plt.Axes,
    positions: list[tuple[float, float]],
    stakes: list[float],
    label: str,
    cmap,
    linestyle: str = "solid",
    linewidth: float = 2.8,
) -> LineCollection | None:
    if len(positions) < 2:
        return None

    segments = [[positions[i], positions[i + 1]] for i in range(len(positions) - 1)]
    lc = LineCollection(
        segments,
        cmap=cmap,
        norm=plt.Normalize(0.0, 1.0),
        linewidth=linewidth,
        linestyles=linestyle,
        label=label,
        alpha=0.8,
    )
    lc.set_array(torch.tensor(stakes, dtype=torch.float32).numpy())
    ax.add_collection(lc)
    return lc


def trajectory_midpoint(positions: list[tuple[float, float]]) -> tuple[float, float]:
    if not positions:
        return (EVAL_START_STATE[0], EVAL_START_STATE[1])
    return positions[len(positions) // 2]


def decorate_trajectory_axes(ax: plt.Axes) -> None:
    obstacle = plt.Circle(
        tuple(OBS_C.tolist()),
        OBS_R,
        color="red",
        alpha=0.25,
        label="Friction zone",
    )
    ax.add_patch(obstacle)
    ax.scatter(
        [GOAL[0].item()],
        [GOAL[1].item()],
        marker="*",
        s=260,
        color="green",
        edgecolor="black",
        linewidth=0.6,
        label="Goal",
        zorder=5,
    )
    ax.scatter(
        [EVAL_START_STATE[0]],
        [EVAL_START_STATE[1]],
        marker="o",
        s=80,
        color="black",
        label="Start",
        zorder=5,
    )
    ax.set_xlabel("x")
    ax.set_ylabel("y")
    ax.set_aspect("equal", adjustable="box")
    ax.set_xlim(0.0, 5.0)
    ax.set_ylim(0.0, 5.0)
    ax.grid(True, alpha=0.25)


def plot_cddp_trajectories(env: DifferentiablePointMassEnv, agent: CDDPAgent) -> None:
    """Save one top-down plot of long-clock vs tight-clock behavior."""
    min_steps, tight_steps = eval_clock_config()
    long_pos, long_stakes = rollout_eval_trajectory(
        env,
        agent,
        clock_max_steps=LONG_CLOCK_STEPS,
        rollout_cap=LONG_CLOCK_STEPS,
    )
    tight_pos, tight_stakes = rollout_eval_trajectory(
        env,
        agent,
        clock_max_steps=tight_steps,
        rollout_cap=tight_steps,
    )

    fig = plt.figure(figsize=(9.2, 8.0), constrained_layout=True)
    grid = fig.add_gridspec(
        2,
        2,
        width_ratios=[1.0, 0.055],
        height_ratios=[1.0, 1.0],
        wspace=0.08,
        hspace=0.22,
    )
    ax = fig.add_subplot(grid[:, 0])
    long_cax = fig.add_subplot(grid[0, 1])
    tight_cax = fig.add_subplot(grid[1, 1])
    decorate_trajectory_axes(ax)

    long_lc = add_stakes_path(
        ax,
        long_pos,
        long_stakes,
        label=f"Long clock ({LONG_CLOCK_STEPS} steps)",
        cmap=plt.cm.cool,
        linestyle="dashed",
        linewidth=2.8,
    )
    tight_lc = add_stakes_path(
        ax,
        tight_pos,
        tight_stakes,
        label=f"Tight clock ({tight_steps} steps)",
        cmap=plt.cm.autumn,
        linestyle="solid",
        linewidth=3.0,
    )
    
    if long_lc is not None:
        cbar1 = fig.colorbar(long_lc, cax=long_cax)
        cbar1.set_label("Long S(s)", labelpad=8)
        cbar1.set_ticks([0.0, 0.5, 1.0])
        cbar1.ax.tick_params(labelsize=8)
    else:
        long_cax.set_visible(False)
    if tight_lc is not None:
        cbar2 = fig.colorbar(tight_lc, cax=tight_cax)
        cbar2.set_label("Tight S(s)", labelpad=8)
        cbar2.set_ticks([0.0, 0.5, 1.0])
        cbar2.ax.tick_params(labelsize=8)
    else:
        tight_cax.set_visible(False)

    ax.set_title(
        f"CDDP Spatio-Temporal Boundary Adaptation\n"
        f"(min={min_steps}, tight={tight_steps})"
    )
    ax.legend(loc="upper left")
    fig.savefig(TRAJECTORY_PLOT_PATH, dpi=180)
    plt.close(fig)


