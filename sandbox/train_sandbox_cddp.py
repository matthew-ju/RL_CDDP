def load_best_checkpoints(agent: CDDPAgent) -> bool:
    """Load the best CDDP-phase weights if they have been saved."""
    actor_path = os.path.join(CHECKPOINT_DIR, "cddp_actor_best.pt")
    z_free_path = os.path.join(CHECKPOINT_DIR, "cddp_z_free_best.pt")
    z_deon_path = os.path.join(CHECKPOINT_DIR, "cddp_z_deon_best.pt")
    if not all(os.path.exists(path) for path in (actor_path, z_free_path, z_deon_path)):
        return False

    try:
        agent.actor.load_state_dict(torch.load(actor_path, map_location=DEVICE))
        agent.z_free.load_state_dict(torch.load(z_free_path, map_location=DEVICE))
        agent.z_deon.load_state_dict(torch.load(z_deon_path, map_location=DEVICE))
    except RuntimeError as exc:
        print(f"  Best checkpoint is incompatible with current architecture: {exc}")
        return False
    return True


def estimate_unobstructed_min_steps() -> int:
    """Estimate the fastest goal reach in open space under current dynamics.

    This ignores the obstacle and CBF but includes dt, U_MAX, v_max, and the
    environment's soft velocity saturation. It is a physical lower bound for
    the selected evaluation start, not a learned-policy guarantee.
    """
    pos = torch.tensor(EVAL_START_STATE[:2], dtype=torch.float32)
    vel = torch.zeros(2, dtype=torch.float32)

    for step in range(1, LONG_CLOCK_STEPS + 1):
        direction = torch.sign(GOAL.cpu() - pos)
        action = U_MAX * direction
        pos = pos + DT * vel
        vel = V_MAX_ENV * torch.tanh((vel + DT * action) / V_MAX_ENV)
        if torch.norm(pos - GOAL.cpu()).item() < GOAL_TOL:
            return step

    raise RuntimeError("Unobstructed minimum-step estimate failed to reach the goal.")


def eval_clock_config() -> tuple[int, int]:
    min_steps = estimate_unobstructed_min_steps()
    return min_steps, TIGHT_CLOCK_STEPS


